local T = dofile('tests/kernel_session_harness.lua')
local H = T.H
local a, b = T.new(false, 'server'), T.new(true, 'server')
local original = H.load(H.qbx .. 'modules/bridge-cache.lua', a.env)('test:changed')
local ported = H.load('kernel/shared/bridge_cache.lua', H.environment())(b.delivery, 'test:changed')
local count = 0
local function run(label, fn)
    H.same(table.pack(fn(ported, b)), table.pack(fn(original, a)), label .. ': return')
    H.same(b.trace, a.trace, label .. ': effects'); H.same(b.cache, a.cache, label .. ': state')
    count = count + 1
end
run('queued while stopped', function(w) w.record('player', {name = 'A', items = {1, 2}, metadata = {health = 200}}); return w.flush('init') end)
assert(#b.trace == 0)
run('stopped patch', function(w) w.patch('player', {name = 'B'}); return w.flush('offline') end)
run('deliver', function(w, r) r.bridge = 'started'; return w.flush('ready') end)
run('idempotence', function(w) return w.flush('same') end)
run('changed only', function(w) w.patch('player', {metadata = {health = 175}}); return w.flush('patch') end)
run('no alias', function(w, r) local delta = {items = {3, 4}}; w.patch('player', delta); delta.items[1] = 999; return w.flush('copy') end)
assert(b.cache.player.items[1] == 3)
run('field removal', function(w) w.record('player', {name = 'C'}); return w.flush('replace') end)
assert(b.cache.player.items == nil)
run('fields insert', function(w) w.fields('m:', {a = 1, b = 2}); return w.flush('fields') end)
run('fields remove', function(w) w.fields('m:', {a = 3}); return w.flush('remove') end)
assert(b.cache['m:b'] == nil)
run('explicit nil', function(w) w.stage('m:a', nil); return w.flush('nil') end)
run('bridge replay', function(w, r) r.cache = {}; return w.flush('bridge-start', true) end)
assert(b.cache.player.name == 'C' and b.cache['m:a'] == nil)
run('stopped replacement', function(w, r) r.bridge = 'stopped'; w.record('player', {name = 'D'}); return w.flush('stopped') end)
run('replay replacement', function(w, r) r.bridge = 'started'; return w.flush('ready', true) end)
run('unknown patch ignored', function(w) w.patch('absent', {x = 1}); return w.flush() end)
run('equal stage', function(w) w.stage('player', {name = 'D'}); return w.flush('same') end)
print('PASS kernel cache writer: ' .. count .. ' differential cases; queue/patch/removal/copy/replay, no hydration')
