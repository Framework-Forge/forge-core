local R=dofile('tests/kernel_server_settings_harness.lua')
local count=0
local function case(n,fn)R.case(n,fn);count=count+1 end
case('start idempotent',function(r)assert(r.b.start());assert(r.b.start());assert(r.b.started)end)
case('normalize history',function(r)
    r.config.DatabaseBackup.Storage.maxHistory=2;r.m.seed(r.config.DatabaseBackup.Storage.historyFile,{{path='A'},false,{path='C'}})
    r.b.start();assert(#r.b.history==1)
end)
case('get history starts',function(r)local ok,h=r.b.getHistory(1);assert(ok and h.entries==r.b.history and r.b.started)end)
case('denied',function(r)r.jobResult=false;assert(not r.b.getHistory(1));assert(not r.b.create(1,'both'))end)
case('console first',function(r)r.jobResult=false;assert(r.b.canManage(0))end)
case('staff overrides job false',function(r)r.services.StaffService={canManage=function()return false end};assert(not r.b.canManage(1))end)
case('staff strict true',function(r)r.services.StaffService={canManage=function()return 1 end};assert(not r.b.canManage(1));r.services.StaffService.canManage=function()return true end;assert(r.b.canManage(1))end)
case('job strict true',function(r)r.jobResult=1;assert(not r.b.canManage(1))end)
case('running',function(r)r.b.running=true;local ok,e=r.b.create(1,'both');assert(not ok and e=='backup_running')end)
for _,mode in ipairs({'schema','data','both','SCHEMA'})do
    case('mode '..mode,function(r)
        local ok,result=r.b.create(1,mode);assert(ok and result.tables==1 and result.path:find('.sql',1,true))
        local sql=assert(r.sqlFiles[result.path])
        assert(type(result.error)=='string'and result.error:find('table: ',1,true),'installed success error-field defect retained')
        assert(sql:find('FOREIGN_KEY_CHECKS',1,true));assert(not r.b.started,'create does not implicitly load history')
    end)
end
for _,mode in ipairs({'bad','dados','',false})do
    case('invalid '..tostring(mode),function(r)local ok,e=r.b.create(1,mode);assert(not ok and e=='invalid_mode')end)
end
case('missing integration',function(r)r.library.database=nil;local ok,e=r.b.create(1,'both');assert(not ok and e=='backup_unavailable')end)
case('not ready',function(r)r.sqlReady=false;local ok,e=r.b.create(1,'both');assert(not ok and e=='database_not_ready')end)
case('no schema',function(r)r.noSchema=true;local ok,e=r.b.create(1,'schema');assert(not ok and e=='players:schema_unavailable')end)
case('PR sql false save',function(r)r.sqlSaved=false;local ok,e=r.b.create(1,'both');assert(not ok and e=='save_failed')end)
case('PR sql nil save accepted',function(r)r.sqlSaved=nil;assert(r.b.create(1,'both'))end)
case('PR sql zero save accepted',function(r)r.sqlSaved=0;assert(r.b.create(1,'both'))end)
case('PR sql exception',function(r)r.sqlWriteError=true;local ok=r.b.create(1,'both');assert(not ok and not r.b.running)end)
case('invalid result',function(r)r.backupHook=function()return true,1 end;local ok,e=r.b.create(1,'both');assert(not ok and e=='invalid_backup_result')end)
case('truthy invalid result throws outside pcall',function(r)r.backupHook=function()return 1,1 end;assert(not pcall(r.b.create,1,'both'));assert(not r.b.running)end)
case('history failure ignored',function(r)r.m.onWrite=function()return false end;local ok,entry=r.b.create(1,'both');assert(ok and entry.success and #r.b.history==0 and next(r.sqlFiles))end)
case('history limit',function(r)r.config.DatabaseBackup.Storage.maxHistory=1;assert(r.b.create(1,'schema'));assert(r.b.create(1,'data'));assert(#r.b.history==1 and r.b.history[1].mode=='data')end)
case('path invalid',function(r)r.config.DatabaseBackup.Storage.directory='../outside';local ok,e=r.b.create(1,'both');assert(not ok and e=='invalid_path')end)
case('same second overwrite inherited',function(r)local ok,a=r.b.create(1,'both');local ok2,b=r.b.create(1,'both');assert(ok and ok2 and a.path==b.path and #r.b.history==2)end)
case('history not loaded before create',function(r)r.m.seed(r.config.DatabaseBackup.Storage.historyFile,{{path='old'}});assert(r.b.create(1,'both'));assert(#r.b.history==1 and not r.b.started)end)
print('PASS database backup differentials '..count)
