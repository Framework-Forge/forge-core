local L = dofile('tests/kernel_lifecycle_harness.lua')
local total = 0
local function scenario(configure, fn)
    local p = L.pair()
    p.run('configure and load', function(r) if configure then configure(r) end; r.loadQueue(); return r.queue == false end)
    fn(p); total = total + p.count
end
local function fork(r, label, src, license)
    r.queueTasks = r.queueTasks or {}
    r.queueTasks[label] = r.fork(function() r.queue.awaitPlayerQueue(src, license, r.deferrals(label)) end, src)
    return r.step(r.queueTasks[label])
end
scenario(function(r) r.queueEnabled = false end, function(p)
    assert(p.b.queue == false and #p.b.events == 0 and #p.b.trace == 0)
    local factory = L.H.load('kernel/server/queue.lua', L.H.environment())
    assert(factory({enabled = false}) == false, 'Disabled queue must need no runtime bindings')
end)
scenario(nil, function(p)
    p.run('other resource starting', function(r) r.dispatch('onResourceStarting', 0, 'other') end)
    p.run('hardcap prevented', function(r) r.dispatch('onResourceStarting', 0, 'hardcap') end)
    p.run('free slot', function(r) return fork(r, 'first', 1, 'license:A') end)
    p.run('reconnect while downloading', function(r) r.queue.awaitPlayerQueue(2, 'license:A', r.deferrals('reconnect')) end)
    p.run('joining arrived', function(r) r.queue.removePlayerJoining('license:A'); return r.step(r.queueTasks.first) end)
    p.run('remove absent', function(r) r.queue.removePlayerJoining('missing') end)
end)
scenario(function(r) r.maxPlayers = 1; r.numPlayers = 1 end, function(p)
    p.run('regular waits', function(r) return fork(r, 'regular', 1, 'license:A') end)
    p.run('waiting emoji wraps', function(r)
        local ok, delay, state
        for _ = 1, 5 do ok, delay, state = r.step(r.queueTasks.regular); assert(ok, delay) end
        return ok, delay, state
    end)
    p.run('duplicate license', function(r) r.queue.awaitPlayerQueue(1, 'license:A', r.deferrals('duplicate')) end)
    p.run('admin overtakes', function(r) r.aces[2] = {admin = true}; return fork(r, 'admin', 2, 'license:B') end)
    p.run('regular position shifts', function(r) return r.step(r.queueTasks.regular) end)
    p.run('third regular', function(r) return fork(r, 'last', 3, 'license:C') end)
    p.run('admin slot released', function(r) r.numPlayers = 0; return r.step(r.queueTasks.admin) end)
    p.run('joining reservation blocks', function(r) return r.step(r.queueTasks.regular) end)
    p.run('admin joined', function(r) r.queue.removePlayerJoining('license:B'); return r.step(r.queueTasks.admin) end)
    p.run('regular now first', function(r) return r.step(r.queueTasks.regular) end)
    p.run('regular joined', function(r) r.queue.removePlayerJoining('license:A'); return r.step(r.queueTasks.regular) end)
    p.run('last advances', function(r) return r.step(r.queueTasks.last) end)
    p.run('last installer disconnect', function(r) r.exists[3] = false; r.now = 5000; return r.step(r.queueTasks.last) end)
end)
scenario(function(r) r.maxPlayers = 1; r.numPlayers = 1 end, function(p)
    p.run('waiting initial', function(r) return fork(r, 'old', 1, 'license:A') end)
    p.run('disconnect waiting', function(r) r.exists[1] = false; return r.step(r.queueTasks.old) end)
    p.run('reconnect within timeout', function(r) r.exists[2] = true; return fork(r, 'new', 2, 'license:A') end)
    p.run('old timeout consumed', function(r) return r.step(r.queueTasks.old) end)
    p.run('new gets slot', function(r) r.numPlayers = 0; return r.step(r.queueTasks.new) end)
    p.run('new joined', function(r) r.queue.removePlayerJoining('license:A'); return r.step(r.queueTasks.new) end)
end)
scenario(function(r)
    r.numPlayers = 10; r.maxPlayers = 1
    r.queueConfigHook = function(config) config.useAdaptiveCard = false end
end, function(p)
    p.run('no card wait', function(r) return fork(r, 'gone', 1, 'license:A') end)
    p.run('timeout begin', function(r) r.exists[1] = false; return r.step(r.queueTasks.gone) end)
    p.run('timeout removes', function(r) return r.step(r.queueTasks.gone) end)
    p.run('next queue empty', function(r) r.numPlayers = 0; return fork(r, 'next', 2, 'license:B') end)
end)
scenario(function(r)
    r.hardcap = 'stopped'; r.queueConfigHook = function(config) config.subQueues = {{name = 'Only admin', predicate = function(src) return r.native.isAceAllowed(src, 'admin') end}} end
end, function(p)
    p.run('no matching subqueue', function(r) r.queue.awaitPlayerQueue(1, 'license:A', r.deferrals('refused')) end)
    p.run('card generator copies', function(r) return r.queueConfig.generateCard({subQueue = {name = 'Custom', cardOptions = {color = 'warning'}}, globalPos = 5, totalQueueSize = 10, displayTime = '00:10'}) end)
end)
print('PASS kernel queue: ' .. total .. ' differential cases; priority/cards/reservations/reconnect/timeouts, explicit hardcap bootstrap only')
