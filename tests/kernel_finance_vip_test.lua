local F=dofile('tests/kernel_finance_harness.lua')
local count=0
local function case(label,action,options)F.case('vip',label,action,options);count=count+1 end
case('tiers sorted clones',function(r)
    local list=r.api.getTiers();local first=list[1].id;list[1].salary.amount=9;assert(r.api.tiers[first].salary.amount~=9);return r.api.getTiers()
end)
case('no membership',function(r)return r.api.get(1),r.exported.GetVipXpMultiplier(1)end)
case('VIP disabled',function(r)return r.api.grant(0,1,'gold',1),r.api.get(1)end,function(r)r.vipConfig.enabled=false end)
case('grant get exports',function(r)
    assert(r.api.grant(0,'1',' Gold ',2.5));assert(r.exported.GetVipXpMultiplier(1)==1.25);return r.exported.GetVip(1)
end)
case('grant denied',function(r)r.allowed=false;return r.api.grant(2,1,'gold',1)end)
for i,args in ipairs({{0,9,'gold',1},{0,1,'missing',1},{0,1,'gold',0},{0,1,'gold','bad'}})do
    case('grant invalid '..i,function(r)return r.api.grant(table.unpack(args))end)
end
case('revoke',function(r)r.api.grant(0,1,'gold',2);return r.api.revoke(0,1),r.api.get(1)end)
case('revoke denied',function(r)r.allowed=false;return r.api.revoke(2,1)end)
case('revoke missing',function(r)return r.api.revoke(0,9)end)
case('expired membership cleared',function(r)
    r.players[1].PlayerData.metadata.vip={tier='gold',expiresAt=r.now,assignedAt=1};return r.api.apply(1)
end)
case('deleted tier metadata cleared',function(r)
    r.players[1].PlayerData.metadata.vip={tier='unknown',expiresAt=r.now+100};return r.api.apply(1)
end)
case('invalid metadata',function(r)r.players[1].PlayerData.metadata.vip='bad';return r.api.get(1)end)
case('invalid player',function(r)return r.api.apply(9)end)
case('tier normalized',function(r)return r.api.upsertTier(0,{id=' New Tier! ',salary={enabled=true,amount=2.9,account='cash'},slots=-3,weight=4.9,xpMultiplier=0})end)
case('tier missing id',function(r)return r.api.upsertTier(0,{})end)
case('tier save denied',function(r)r.allowed=false;return r.api.upsertTier(1,{id='new'})end)
case('tier save fails',function(r)r.memory.onWrite=function()return false end;return r.api.upsertTier(0,{id='new'})end)
case('tier edit applies online',function(r)r.api.grant(0,1,'gold',1);return r.api.upsertTier(0,{id='gold',salary={enabled=true,amount=5}})end)
case('delete tier in use',function(r)r.api.grant(0,1,'gold',1);return r.api.deleteTier(0,'gold')end)
case('delete unused',function(r)return r.api.deleteTier(0,'bronze')end)
case('delete missing',function(r)return r.api.deleteTier(0,'missing')end)
case('delete denied',function(r)r.allowed=false;return r.api.deleteTier(1,'bronze')end)
case('bonus applied once',function(r)r.api.grant(0,1,'gold',1);r.step()end)
case('bonus revision cancels old worker',function(r)
    r.api.grant(0,1,'gold',1);r.api.revoke(0,1);r.step(1);r.step(2)
end)
case('bonus retries',function(r)
    r.api.grant(0,1,'gold',1);r.bonusResults={table.pack(false,'not_ready'),table.pack(true,'ok')}
    assert(r.step()==50);r.step()
end)
case('bonus slot limit pending reset',function(r)
    r.api.clearSession(1,true);r.bonusResults={table.pack(false,'slot_limit_below_item_count')}
    r.step();assert(r.api.pendingInventoryReset[1])
end)
case('bonus stopped timeout pending',function(r)
    r.inventoryReady=false;r.api.clearSession(1,true)
    assert(r.step()==50);assert(r.step()==50);r.step();assert(r.api.pendingInventoryReset[1])
end)
case('bonus exception retried',function(r)
    r.api.clearSession(1,true);r.bonusResults={'throw',table.pack(true)};assert(r.step()==50);r.step()
end)
case('bonus player left',function(r)r.api.clearSession(1,true);r.players[1]=nil;r.step()end)
case('clear no reset',function(r)r.api.grant(0,1,'gold',1);r.api.clearSession(1,false)end)
case('loaded timer',function(r)r.api.grant(0,1,'gold',1);r.dispatch('QBCore:Server:OnPlayerLoaded',1);r.runTimers()end)
case('drop cleanup',function(r)r.api.grant(0,1,'gold',1);r.dispatch('playerDropped',1)end)
case('resource timer gates',function(r)
    r.dispatch('onResourceStart',0,'unrelated');r.dispatch('onResourceStart',0,'forge-core');r.dispatch('onResourceStart',0,'ox_inventory');r.runTimers()
end)
case('expiration worker descriptor',function(r)
    r.api.grant(0,1,'gold',1);r.tasks[#r.tasks+1]=coroutine.create(r.threads[1]);local index=#r.tasks
    assert(r.step(index)==15000);r.now=r.now+86401;assert(r.step(index)==15000);assert(not r.api.sessions[1])
end)
case('late inventory worker new source inherited',function(r)
    r.api.grant(0,1,'gold',1);r.players[1]=r.makePlayer(1);r.players[1].PlayerData.citizenid='NEW';r.step()
    assert(r.api.sessions[1],'old session still present unless lifecycle drop installed')
end)
local r=F.new(true,'vip');assert(not r.api.Initialize(),'explicit initialization once')
print(('PASS finance VIP: %d differential cases; all tier/admin/get/session/bonus/retry/ACE/events/expiry behavior, explicit initialization and retained source ownership limits'):format(count))
