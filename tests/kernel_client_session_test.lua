local T = dofile('tests/kernel_session_harness.lua')
local total = 0
local function scenario(fn)
    local p = T.pair('client', {'bridge_cache', 'session', 'status'})
    fn(p); total = total + p.count
end
scenario(function(p)
    p.run('snapshot before load', function(r) return r.core.Session.snapshot(), r.core.Session.isDead() end)
    p.run('bridge replay', function(r) r.bridge = 'started'; r.dispatch('onClientResourceStart', 0, 'pr_bridge') end)
    p.run('publish player', function(r) r.core.BridgeCache.player(r.core.PlayerData, 'payload') end)
    p.run('load', function(r) r.dispatch('QBCore:Client:OnPlayerLoaded', 0); return r.core.Session.snapshot() end)
    p.run('initial status', function(r) r.dispatch('qbx_core:client:statusUpdated', 0, {health = 72, armor = 20, hunger = 60, thirst = 50, oxygen = 100, hungerRate = 3, thirstRate = 4, nextDecaySeconds = 1, decayIntervalSeconds = 60}) end)
    p.run('query status', function(r) return r.exported.GetStatus(), r.exported.GetStatus('invalid') end)
    p.run('no change', function(r) return r.exported.SetStatus('hunger', 60) end)
    p.run('clamp set', function(r) return r.exported.SetStatus('hunger', 1000) end)
    p.run('large legacy delta', function(r) return r.exported.AddStatus('stress', 100000) end)
    p.run('effects', function(r) return r.exported.AddStatuses({hunger = -10, thirst = 5, invalid = 20}) end)
    p.run('invalid values', function(r) return r.exported.AddStatuses(false) end)
    p.run('native query', function(r) r.health = 160; r.armor = 45; r.dispatch('qbx_core:client:refreshNativeStatus', 0) end)
    p.run('persistence land oxygen', function(r) r.exported.SetStatus('oxygen', 35); return r.callbacks['qbx_core:client:getStatusSnapshot']() end)
    p.run('persistence underwater', function(r) r.water = true; return r.callbacks['qbx_core:client:getStatusSnapshot']() end)
    p.run('flush loaded', function(r) return r.exported.FlushStatusSnapshot('manual') end)
    p.run('context vehicle', function(r) r.vehicle = 20; return r.exported.RefreshClientContext('vehicle') end)
    p.run('bad context refused', function(r) return r.exported.PublishClientContext(false) end)
    p.run('explicit context', function(r) return r.exported.PublishClientContext({vehicle = false, seat = false, ignored = 99}) end)
    p.run('metadata refresh', function(r) r.core.PlayerData.metadata.ishandcuffed = true; r.core.Session.refresh(); return r.core.Session.snapshot() end)
    p.run('unload', function(r) r.dispatch('QBCore:Client:OnPlayerUnload', 0); return r.core.Session.snapshot(), r.exported.GetStatus(), r.exported.FlushStatusSnapshot() end)
    assert(p.b.cache.playerLoaded == false)
    p.run('new character', function(r) r.core.PlayerData = {citizenid = 'B', metadata = {health = 200}, money = {cash = 2}}; r.core.BridgeCache.player(r.core.PlayerData); r.dispatch('QBCore:Client:OnPlayerLoaded', 0); return r.core.Session.snapshot() end)
    assert(p.b.cache['metadata:self:ishandcuffed'] == nil)
    p.run('stop flush', function(r) r.dispatch('onResourceStop', 0, 'forge-core') end)
    p.run('unrelated stop', function(r) r.dispatch('onResourceStop', 0, 'other') end)
end)
scenario(function(p)
    p.run('unloaded loops', function(r) return r.step(1), r.step(2), r.step(3), r.step(4) end)
    p.run('persisted death', function(r) r.core.PlayerData.metadata.isdead = true; r.dispatch('QBCore:Client:OnPlayerLoaded', 0) end)
    p.run('death enforcer', function(r) r.health = 200; return r.step(1) end)
    p.run('override caller denied', function(r) r.invoking = 'other'; r.dispatch('qbx_core:client:setDeathPoseOverride', 0, true); return r.step(1) end)
    p.run('override accepted', function(r) r.invoking = 'forge-core'; r.dispatch('qbx_core:client:setDeathPoseOverride', 0, true); return r.step(1) end)
    p.run('native death snapshot', function(r) r.dead = true; return r.step(4), r.step(4) end)
end)
scenario(function(p)
    p.run('load for decay', function(r) r.dispatch('QBCore:Client:OnPlayerLoaded', 0); r.dispatch('qbx_core:client:statusUpdated', 0, {hungerRate = 3, thirstRate = 4, nextDecaySeconds = 1, decayIntervalSeconds = 60}); return r.step(4) end)
    p.run('decay catches up', function(r) r.now = 121000; return r.step(4) end)
    assert(p.b.exported.GetStatus('hunger') == 91 and p.b.exported.GetStatus('thirst') == 88)
    p.run('debounced save', function(r) r.now = 122000; return r.step(4) end)
    p.run('stamina-only no dirty save', function(r) r.stamina = 30; r.now = 122600; return r.step(4) end)
    p.run('driving stress', function(r) r.vehicle = 20; return r.step(2) end)
    p.run('buckled threshold', function(r) r.dispatch('forge-hud:client:seatbeltChanged', 0, true); r.speed = 20; return r.step(2) end)
    p.run('police exemption', function(r) r.core.PlayerData.job = {name = 'police'}; r.speed = 40; return r.step(2) end)
    p.run('shooting stress', function(r) r.core.PlayerData.job = {name = 'taxi'}; r.weapon = 123; r.shooting = true; return r.step(3) end)
    p.run('whitelisted weapon', function(r) r.clientConfig.stress.whitelistedWeapons = {[123] = true}; return r.step(3) end)
end)
print('PASS kernel client producers: ' .. total .. ' differential cases; native effects/death/stress/decay/debounce, passive cache/session')
