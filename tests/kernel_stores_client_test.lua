local R=dofile('tests/kernel_stores_harness.lua')
local H=R.H;local n=0
local function case(name,fn)R.clientCase(name,fn);n=n+1 end
case('multiple targets one primary blip',function(r)
    r.apply(R.seed());assert(r.stores.ready and #r.stores.zones==2 and #r.stores.blips==1)
    assert(r.targets[1].name=='forge_core_store_market_1'and r.targets[2].name=='forge_core_store_market_2')
end)
case('financial stock update no target rebuild',function(r)
    local p=R.seed();r.apply(p);local count=r.targetId;p=H.copy(p);p.stores[1].balance=999;p.stores[1].stock.burger=6;p.revision=2
    r.apply(p);assert(r.targetId==count and #r.stores.blips==1 and r.stores.payload==p)
end)
for _,field in ipairs({'label','targetLabel','purchasePrice','owner','saleListed','rotation','enabled'})do case('zone field '..field,function(r)
    local p=R.seed();r.apply(p);p=H.copy(p)
    p.stores[1][field]=({label='New',targetLabel='Open',purchasePrice=777,owner='CID2',saleListed=true,rotation=45,enabled=false})[field]
    r.apply(p);assert(field=='enabled'and #r.stores.zones==0 or r.targetId==4)
end)end
case('point changes rebuild',function(r)local p=R.seed();r.apply(p);p=H.copy(p);p.stores[1].points[2].coords.x=8;r.apply(p);assert(r.targetId==4)end)
case('legacy coords target',function(r)local p=R.seed();p.stores[1].points={};p.stores[1].coords={x=1,y=2,z=3};r.apply(p);assert(#r.stores.zones==1)end)
case('disabled all clears',function(r)r.apply(R.seed());r.apply({settings={enabled=false},stores={}});assert(#r.stores.zones==0 and #r.stores.blips==0)end)
case('nil payload becomes ready empty',function(r)r.apply(nil);assert(r.stores.ready and #r.stores.zones==0)end)
case('bad point vector skips',function(r)r.vectorError=true;r.apply(R.seed());assert(not r.stores.ready)end)
case('target exception marks not ready retry',function(r)r.targetError=true;r.apply(R.seed());assert(not r.stores.ready);r.targetError=false;r.apply(R.seed());assert(r.stores.ready)end)
case('target false marks not ready',function(r)r.targetFalse=true;r.apply(R.seed());assert(not r.stores.ready)end)
case('missing target module',function(r)r.library.target=nil;r.apply(R.seed());assert(not r.stores.ready)end)
case('no blip if disabled',function(r)local p=R.seed();p.stores[1].blip.enabled=false;r.apply(p);assert(#r.stores.blips==0)end)
case('buy option uses same canonical menu',function(r)
    r.menu.openStoreInventory=function(id)r.record('open-menu-inventory',id)end;r.apply(R.seed());r.targets[1].options[1].onSelect()
end)
case('unavailable menu notifies',function(r)r.apply(R.seed());r.targets[1].options[1].onSelect()end)
case('open storefront callback',function(r)
    r.menu.openStorefront=function(id)r.record('open-menu-front',id)end;r.apply(R.seed());r.targets[1].options[2].onSelect()
end)
for _,identity in ipairs({'CID1','CID2',''})do case('owner permission '..identity,function(r)
    local p=R.seed();p.stores[1].owner='CID1';r.playerData.citizenid=identity;r.apply(p)
    assert(r.targets[1].options[2].canInteract()==(identity=='CID1'))
end)end
case('manager string',function(r)local p=R.seed();p.stores[1].owner='OTHER';p.stores[1].managers={'CID1'};r.apply(p);assert(r.targets[1].options[2].canInteract())end)
case('manager table',function(r)local p=R.seed();p.stores[1].owner='OTHER';p.stores[1].managers={{citizenid='CID1'}};r.apply(p);assert(r.targets[1].options[2].canInteract())end)
case('identifier fallback',function(r)local p=R.seed();p.stores[1].owner='CID1';r.playerData={identifier='CID1'};r.apply(p);assert(r.targets[1].options[2].canInteract())end)
case('sale option rejects own owner',function(r)local p=R.seed();p.stores[1].owner='CID1';p.stores[1].saleListed=true;r.apply(p);assert(#r.targets[1].options==3 and not r.targets[1].options[3].canInteract())end)
case('worker waits and hydrates',function(r)
    r.value=R.seed();local co=coroutine.create(r.initial[1]);local ok,delay=coroutine.resume(co);assert(ok and delay==2000)
    assert(coroutine.resume(co));assert(r.stores.ready)
end)
case('loaded lifecycle hydrates',function(r)r.value=R.seed();r.fireStore('pr_bridge:client:OnPlayerLoaded');assert(r.stores.ready)end)
case('bridge stop invalidates known target ids',function(r)r.apply(R.seed());r.fireStore('onClientResourceStop','pr_bridge');assert(not r.stores.ready and #r.stores.zones==0 and #r.stores.blips==0)end)
case('bridge start deferred hydrate',function(r)r.value=R.seed();r.fireStore('onClientResourceStart','pr_bridge');assert(not r.stores.ready);r.advance(0);assert(r.stores.ready)end)
case('unrelated lifecycle ignored',function(r)r.apply(R.seed());r.fireStore('onResourceStop','other');r.fireStore('onClientResourceStop','other');assert(r.stores.ready)end)
case('own stop clears handles',function(r)r.apply(R.seed());r.fireStore('onResourceStop','forge-core');assert(#r.stores.zones==0 and #r.stores.blips==0)end)
case('same payload reference inherited no change detection',function(r)local p=R.seed();r.apply(p);p.stores[1].label='Changed';r.apply(p);assert(r.targetId==2)end)
print('PASS stores client/target differentials '..n)
