local R=dofile('tests/kernel_skill_client_harness.lua')
local n=0
local function case(label,fn)R.case(label,fn);n=n+1 end
case('constructor is inert',function(r)
    assert(#r.trace==0 and #r.events==4 and #r.threads==1)
    assert(r.exports.fetchSkills()==nil and r.exports.getCurrentSkill('a')==0 and r.exports.getSkillInfo('a')==nil)
    return r.collect()
end)
case('full sync and copy isolation',function(r)
    r.sync(R.packet());assert(r.exports.getCurrentSkill('sum')==5)
    local p=r.exports.fetchSkills();p.values.a=100
    local info=r.exports.getSkillInfo('a');info.label='other'
    assert(r.exports.getCurrentSkill('a')==10 and r.exports.getSkillInfo('a').label=='Alpha')
    return r.exports.getCurrentLevel('a'),r.exports.getCurrentLevel('none')
end)
for _,amount in ipairs({1,-5,1000,-1000,0,0.123456,'bad',math.huge,-math.huge,0/0})do
    case('update '..tostring(amount),function(r)
        r.sync(R.packet());return r.exports.updateSkill('a',amount)
    end)
end
case('unknown and sum',function(r)
    r.sync(R.packet());return table.pack(r.exports.updateSkill('missing',1)),table.pack(r.exports.updateSkill('sum',1))
end)
case('disabled definitions',function(r)
    local packet=R.packet();packet.definitions.settings.enabled=false;r.sync(packet)
    return r.exports.updateSkill('a',1)
end)
case('decay-only direction',function(r)
    r.sync(R.packet());local a,b=r.exports.updateSkill('free',1)
    assert(not a and b=='client_gain_disabled')
    assert(r.exports.updateSkill('free',-2));return r.exports.getCurrentSkill('free')
end)
case('definitions before token but update not loaded',function(r)
    r.sync({definitions=R.definitions()})
    return r.exports.updateSkill('a',1),r.exports.getSkillInfo('a')
end)
case('nil sync ignored',function(r)r.sync(nil);return r.exports.fetchSkills()end)
case('invalid sync keeps definitions',function(r)
    local packet=R.packet();packet.values=nil;r.sync(packet)
    assert(r.exports.getSkillInfo('a').label=='Alpha' and r.exports.fetchSkills()==nil)
    return true
end)
case('malformed definitions throws inherited',function(r)
    r.sync({definitions=true});return true
end)
case('same token lower revision ignored',function(r)
    r.sync(R.packet());r.sync({token='session:1',revision=0,values={a=90},ack={}})
    assert(r.exports.getCurrentSkill('a')==10);return true
end)
case('stale definitions overwrite before revision rejection',function(r)
    r.sync(R.packet());local p=R.packet();p.revision=0;p.definitions.skills[1].label='OLD';p.values.a=80;r.sync(p)
    assert(r.exports.getCurrentSkill('a')==10 and r.exports.getSkillInfo('a').label=='OLD')
    return r.exports.fetchSkills()
end)
case('pending predictions survive newer award',function(r)
    r.sync(R.packet());assert(r.exports.updateSkill('a',5))
    r.sync({token='session:1',revision=2,values={a=20,rep=5,free=10},ack={}})
    assert(r.exports.getCurrentSkill('a')==25);return r.collect()
end)
case('acked predictions stop replay',function(r)
    r.sync(R.packet());assert(r.exports.updateSkill('a',5))
    r.sync({token='session:1',revision=2,values={a=15,rep=5,free=10},ack={a={gain=5,loss=0}}})
    assert(r.exports.getCurrentSkill('a')==15);return r.collect()
end)
case('new token resets counters despite lower revision',function(r)
    r.sync(R.packet());assert(r.exports.updateSkill('a',5))
    r.sync({token='session:old',revision=0,values={a=2},ack={}})
    assert(r.exports.getCurrentSkill('a')==2);return r.collect()
end)
case('unload rejects sync and clears cache',function(r)
    r.sync(R.packet());r.event('QBCore:Client:OnPlayerUnload');r.sync(R.packet())
    assert(r.exports.fetchSkills()==nil and r.cache['forge-core:skills']==nil)
    return r.collect()
end)
case('load accepts stale token without generation',function(r)
    r.sync(R.packet());r.event('QBCore:Client:OnPlayerUnload');r.event('QBCore:Client:OnPlayerLoaded');r.sync(R.packet())
    assert(r.exports.getCurrentSkill('a')==10);return true
end)
case('missing own levels uses defaults',function(r)
    r.sync(R.packet());return r.exports.getCurrentLevel('a')
end)
case('empty own levels bypass defaults',function(r)
    local p=R.packet();p.definitions.skills[1].levels={};r.sync(p)
    assert(r.exports.getCurrentLevel('a').title=='Maestria');return true
end)
case('level gaps produce mastery',function(r)
    local p=R.packet();p.definitions.skills[1].levels={{title='Later',from=20,to=30}};r.sync(p)
    assert(r.exports.getCurrentLevel('a').index==1);return r.exports.fetchSkills()
end)
case('sum cap and reputation edits',function(r)
    local p=R.packet();p.values.rep=60;r.sync(p)
    assert(r.exports.getCurrentSkill('sum')==50);assert(r.exports.updateSkill('rep',-40))
    assert(r.exports.getCurrentSkill('sum')==20);return true
end)
print('PASS skill client runtime differentials '..n)

