local N=dofile('tests/kernel_multijob_harness.lua')
local function jobs(r,list,settings)
    r.reply(r.config.MultiJob.Callbacks.getPlayerJobs,true,{jobs=list,settings=settings or{allowPlayerRemove=true}})
end
local taxi={name='taxi',label='Taxi',grade=0,gradeLabel='Driver',payment=20,active=false,onDuty=false,removable=true}
local police={name='police',label='Police',grade=4,gradeLabel='Chief',payment=100,active=true,onDuty=true,removable=false}
N.uiCase('player no jobs',function(r)return r.menu.openMultiJobMenu()end)
N.uiCase('custom parent and details',function(r)jobs(r,{taxi,police});r.menu.openMultiJobMenu('parent');r.select(1);return r.last end)
N.uiCase('active duty description',function(r)jobs(r,{police});return r.menu.openMultiJobMenu()end)
N.uiCase('jobs load failure',function(r)r.reply(r.config.MultiJob.Callbacks.getPlayerJobs,false,'denied');return r.menu.openMultiJobMenu()end)
N.uiCase('malformed player payload',function(r)r.reply(r.config.MultiJob.Callbacks.getPlayerJobs,true,'bad');return r.menu.openMultiJobMenu()end)
N.uiCase('malformed nested jobs',function(r)r.reply(r.config.MultiJob.Callbacks.getPlayerJobs,true,{jobs='bad',settings='bad'});return r.menu.openMultiJobMenu()end)
N.uiCase('disabled active UI option',function(r)r.menu.openMultiJobDetails(police,{});r.select(1);return #r.timers end)
N.uiCase('inactive activate timer',function(r)r.menu.openMultiJobDetails(taxi,{},'parent');r.select(1);r.runTimers(500);return r.last end)
N.uiCase('activate failure timer',function(r)r.reply(r.config.MultiJob.Callbacks.setActiveJob,false,'failed');r.menu.openMultiJobDetails(taxi,{});r.select(1);r.runTimers(500)end)
N.uiCase('activate lock blocks rapid repeat',function(r)r.menu.openMultiJobDetails(taxi,{});r.select(1);r.select(1);return #r.timers end)
N.uiCase('activate await exception retains lock',function(r)
    r.menu.openMultiJobDetails(taxi,{});r.awaitError=true;assert(not pcall(r.select,1));r.awaitError=false;r.select(1);return #r.timers
end)
for _,answer in ipairs({'cancel','confirm'})do
    N.uiCase('remove '..answer,function(r)r.alerts={answer};r.menu.openMultiJobDetails(taxi,{},'parent');r.select(2);r.runTimers(500)end)
end
N.uiCase('remove failure',function(r)
    r.alerts={'confirm'};r.reply(r.config.MultiJob.Callbacks.removeOwnJob,false,'active')
    r.menu.openMultiJobDetails(taxi,{});r.select(2);r.runTimers(500)
end)
N.uiCase('remove checks lock after dialog',function(r)
    r.alerts={'confirm'};r.menu.openMultiJobDetails(taxi,{});r.select(1);r.select(2);return #r.timers
end)
N.uiCase('remove awaits error lock',function(r)
    r.alerts={'confirm','confirm'};r.menu.openMultiJobDetails(taxi,{});r.awaitError=true;assert(not pcall(r.select,2));r.awaitError=false;r.select(2);return #r.timers
end)
N.uiCase('admin settings summary',function(r)
    r.reply(r.config.MultiJob.Callbacks.getSettings,true,{enabled=true,maxJobs=6,allowPlayerRemove=true,blockedJobs={'taxi','police'}})
    r.menu.openMultiJobAdminMenu();r.select(1)
end)
N.uiCase('admin denied defaults UI',function(r)r.reply(r.config.MultiJob.Callbacks.getSettings,false,'no_permission');r.menu.openMultiJobAdminMenu()end)
N.uiCase('admin malformed settings',function(r)r.reply(r.config.MultiJob.Callbacks.getSettings,true,'bad');r.menu.openMultiJobAdminMenu()end)
for i=2,5 do
    N.uiCase('admin navigation '..i,function(r)r.menu.openMultiJobAdminMenu();r.select(i)end)
end
N.uiCase('settings cancel',function(r)r.menu.openMultiJobSettingsEditor({})end)
N.uiCase('settings empty blocked translated none default',function(r)r.menu.openMultiJobSettingsEditor({blockedJobs={}})end)
N.uiCase('settings save normalizes submitted array only',function(r)
    r.inputs={{'true',-1,'false',' Taxi , police\nmechanic'}}
    r.menu.openMultiJobSettingsEditor({includeCurrentJob=false});local args=r.lastRequest();assert(args[4].includeCurrentJob==true)
    r.runTimers(500)
end)
N.uiCase('settings forces current and label parsed',function(r)
    r.inputs={{'false','bad','true','common.none'}};r.menu.openMultiJobSettingsEditor('bad');return r.lastRequest()
end)
N.uiCase('settings save failure',function(r)
    r.inputs={{'true',3,'true',''}};r.reply(r.config.MultiJob.Callbacks.saveSettings,false,'save_failed')
    r.menu.openMultiJobSettingsEditor({});r.runTimers(500)
end)
N.uiCase('settings no lock duplicate submit',function(r)
    r.inputs={{'true',3,'true',''},{'false',1,'false','taxi'}};r.menu.openMultiJobSettingsEditor({});r.menu.openMultiJobSettingsEditor({});return #r.timers
end)
N.uiCase('admin add cancel',function(r)r.menu.openMultiJobAdminAdd()end)
N.uiCase('admin add success',function(r)r.inputs={{'1','TAXI','2'}};r.menu.openMultiJobAdminAdd();r.runTimers(500)end)
N.uiCase('admin add failure',function(r)r.inputs={{'bad',false,'bad'}};r.reply(r.config.MultiJob.Callbacks.addJob,false,'invalid_player');r.menu.openMultiJobAdminAdd();r.runTimers(500)end)
N.uiCase('admin remove cancel',function(r)r.menu.openMultiJobAdminRemove()end)
N.uiCase('admin remove success',function(r)r.inputs={{'1','Taxi'}};r.menu.openMultiJobAdminRemove();r.runTimers(500)end)
N.uiCase('admin remove failure',function(r)r.inputs={{'1','Taxi'}};r.reply(r.config.MultiJob.Callbacks.removeJob,false,'not_found');r.menu.openMultiJobAdminRemove();r.runTimers(500)end)
N.uiCase('admin view cancel',function(r)r.menu.openMultiJobAdminView()end)
N.uiCase('admin view empty',function(r)r.inputs={{'1'}};r.menu.openMultiJobAdminView()end)
N.uiCase('admin view jobs',function(r)
    r.inputs={{'1'}};r.reply(r.config.MultiJob.Callbacks.getTargetJobs,true,{jobs={taxi,police}});r.menu.openMultiJobAdminView()
end)
N.uiCase('admin view malformed',function(r)
    r.inputs={{'1'}};r.reply(r.config.MultiJob.Callbacks.getTargetJobs,true,{jobs='bad'});r.menu.openMultiJobAdminView()
end)
N.uiCase('admin view failure timer',function(r)
    r.inputs={{'1'}};r.reply(r.config.MultiJob.Callbacks.getTargetJobs,false,'no_permission');r.menu.openMultiJobAdminView();r.runTimers(500)
end)
N.uiCase('stale closure submits after config change',function(r)
    r.menu.openMultiJobDetails(taxi,{});r.config.MultiJob.Defaults.enabled=false;r.select(1);r.runTimers(500)
end)
N.uiCase('timer reopens after caller closes UI',function(r)
    r.menu.openMultiJobDetails(taxi,{},'parent');r.select(1);r.last=nil;r.runTimers(500);assert(r.last)
end)
N.uiCase('renderer false ignored',function(r)r.uiReturn=false;return r.menu.openMultiJobMenu()end)
print('PASS multijob menus: '..N.count..' differential cases; all seven installed menus, parent/dialog/options/payload/locks/timers/RPC/error effects, no real NUI')

