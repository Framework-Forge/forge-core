    local r={callbacks={},removed={}}
    r.api=create({isCurrent=function()return not r.stale end})
    r.register,r.remove=r.api.Wrap(function(name,fn,options)
        r.callbacks[name]=fn;if r.hook then r.hook()end;return name,nil,false,options
    end,function(token)r.removed[#r.removed+1]=token;return not r.failRemove end)
    return r
end
