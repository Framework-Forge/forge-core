local T=dofile('tests/kernel_shutdown_harness.lua');local checks=0
local function test(name,fn)fn();checks=checks+1;print('PASS '..name)end
test('constructor inert and one owned holder',function()
    local r=T.unit();r.prepare();assert(#r.trace==0 and not pcall(r.prepare));assert(r.api.Progress().phase=='prepared')
end)
test('install has no worker start and start is explicit once',function()
    local r=T.unit();r.prepare();assert(r.api.Install()and r.live and r.installed==5)
    for _,v in ipairs(r.trace)do assert(v~='start')end
    assert(not r.api.Install()and r.api.Start()and not r.api.Start())
end)
test('revocation then reverse disposal precedes bodies',function()
    local r=T.unit();r.prepare();r.api.Install();r.trace={};assert(r.api.Stop())
    T.H.same(r.trace,{'inactive','close','dispose5','dispose4','dispose3','dispose2','dispose1','detach','body1','body2','body3'})
    assert(r.api.Progress().complete)
end)
test('manual stop waits for quiescence and polls without timer',function()
    local r=T.unit();r.prepare();r.api.Install();r.quiescent=false
    local ok,why=r.api.Stop();assert(not ok and why=='workers_pending'and not r.counts[1]and not r.live)
    r.quiescent=true;assert(r.api.Poll()and r.api.Progress().complete)
end)
test('native stop records best effort with running task',function()
    local r=T.unit();r.prepare();r.api.Install();r.quiescent=false;r.callbacks[1]()
    local p=r.api.Progress();assert(p.nativeBestEffort and not p.complete and r.counts[3]==1)
    r.quiescent=true;assert(r.api.Poll()and r.counts[3]==1)
end)
test('duplicate stop and stale native listener never replay bodies',function()
    local r=T.unit();r.prepare();r.api.Install();r.api.Stop();r.callbacks[1]();r.api.Stop();r.api.Poll()
    assert(r.counts[1]==1 and r.counts[3]==1 and not r.api.Progress().nativeBestEffort)
end)
test('body failure preserves next cleanup and diagnostics',function()
    local r=T.unit();r.prepare();r.api.Install();r.failBody=2;assert(not r.api.Stop())
    assert(r.counts[3]==1 and r.api.Progress().ledger[2]=='failed'and #r.api.Progress().errors==1)
    r.api.Stop();assert(r.counts[2]==1)
end)
test('dispose failure does not hide independent body cleanup',function()
    local r=T.unit();r.prepare();r.api.Install();r.failDispose=4;r.api.Stop()
    assert(r.counts[3]==1 and not r.api.Progress().registrationsRevoked and not r.api.Progress().complete)
end)
test('failure during install closes and never starts suffix binders',function()
    local r=T.unit();r.failInstall=3;r.prepare();assert(not r.api.Install())
    assert(r.installed==3 and r.detached and not r.live and not r.api.Start()and r.counts[3]==1)
end)
test('stop during publication defers disposal until install unwinds',function()
    local r=T.unit();r.prepare();r.installHook=function(i)if i==2 then
        r.api.Stop();for _,v in ipairs(r.trace)do assert(not v:match('dispose'))end
    end end
    assert(not r.api.Install()and r.installed==2 and r.detached and r.counts[1]==1)
end)
test('stop before listener token return still removes owned late token',function()
    local r=T.unit();r.prepare();r.attachHook=function(fn)fn()end
    assert(not r.api.Install()and r.detached and r.installed==0 and r.counts[1]==1)
end)
test('reentrant stop from disposal never duplicates bodies',function()
    local r=T.unit();r.prepare();r.api.Install();r.disposeHook=function()assert(not r.api.Stop())end
    assert(r.api.Stop()and r.counts[1]==1)
end)
test('entered body yield cannot replay and preserves suffix order',function()
    local r=T.unit();r.prepare();r.api.Install();r.bodyHook=function(i)if i==1 then coroutine.yield('body')end end
    local co=coroutine.create(r.api.Stop);assert(coroutine.resume(co));assert(not r.api.Stop()and not r.counts[2])
    assert(coroutine.resume(co)and r.counts[1]==1 and r.counts[3]==1)
end)
test('stale graph revokes own registrations but skips domain bodies',function()
    local r=T.unit();r.prepare();r.api.Install();r.stale=true;assert(not r.api.Stop())
    assert(r.detached and r.counts[1]==nil and r.api.Progress().ledger[1]=='skipped-stale')
end)
test('copied progress and public fields cannot reopen closed scope',function()
    local r=T.unit();r.prepare();r.api.Stop();local p=r.api.Progress();p.phase='installed';p.ledger[1]='pending';r.api.State='installed'
    assert(not r.api.Start()and not r.api.Install()and r.api.Progress().ledger[1]=='completed')
end)
test('stop while Start waits defers cleanup until caller returns',function()
    local r=T.unit();r.prepare();r.api.Install();r.startHook=function()coroutine.yield('starting');return false,'cancelled'end
    local co=coroutine.create(r.api.Start);assert(coroutine.resume(co));r.api.Stop()
    assert(not r.counts[1]and not r.api.Progress().workersQuiescent)
    assert(coroutine.resume(co)and r.counts[3]==1 and r.api.Progress().complete)
end)
test('methods captured before public API replacement',function()
    local r=T.unit();r.prepare();r.api.Install();r.spec.worker.Close=function()error('replacement')end
    r.spec.binders[5].api.Dispose=function()error('replacement')end
    assert(r.api.Stop()and r.counts[3]==1)
end)
test('listener removal failure remains incomplete',function()
    local r=T.unit();r.prepare();r.api.Install();r.failDetach=true;r.api.Stop()
    assert(not r.api.Progress().complete and r.counts[1]==1 and #r.api.Progress().errors==1)
end)
test('manual drain also waits for entered ingress callbacks',function()
    local r=T.unit();r.prepare();r.api.Install();r.pending=1;assert(not r.api.Stop()and not r.counts[1])
    r.pending=0;assert(r.api.Poll()and r.counts[1]==1)
end)
test('native cleanup keeps historical in-flight evidence after drain',function()
    local r=T.unit();r.prepare();r.api.Install();r.pending=1;r.callbacks[1]()
    assert(r.api.Progress().cleanupHadInFlight and not r.api.Progress().complete)
    r.pending=0;r.api.Poll();assert(r.api.Progress().complete and r.api.Progress().cleanupHadInFlight)
end)
