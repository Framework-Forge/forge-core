local T = dofile('tests/kernel_session_harness.lua')
local p = T.pair('server', {'bridge_cache', 'session', 'status'})
local function run(label, fn) return p.run(label, fn) end
run('initial snapshot', function(r) return r.core.Session.snapshot(1) end)
run('not spawned', function(r) return r.core.Session.isLoaded(1) end)
run('login event', function(r) r.bridge = 'started'; r.dispatch('QBCore:Server:PlayerLoaded', 0, r.core.Players[1]) end)
run('spawn', function(r) r.dispatch('QBCore:Server:OnPlayerLoaded', 1); return r.core.Session.snapshot(1) end)
assert(p.b.core.Session.isLoaded(1))
run('copy isolation', function(r) local s = r.core.Session.snapshot(1); s.data.dead = true; return r.core.Session.snapshot(1) end)
run('death and handcuffs', function(r)
    r.core.Players[1].PlayerData.metadata.isdead = true
    r.core.Players[1].PlayerData.metadata.ishandcuffed = true
    r.dispatch('qbx_core:server:onSetMetaData', 0, 'isdead', false, true, 1)
    return r.core.Session.snapshot(1)
end)
run('bucket update', function(r) r.bucket = 22; r.dispatch('qbx_core:server:bucketChanged', 0, 1); return r.core.Session.snapshot(1) end)
run('invalid domains', function(r) return r.exported.GetCachedState('no'), r.exported.GetCachedState(1), r.exported.IsPlayerLoaded('invalid') end)
run('status initialize', function(r) return r.core.Status.Initialize(1) end)
run('status normalize', function(r) return r.core.Status.AcceptSnapshot(1, {health = 150, armor = -30, hunger = '35', oxygen = 11, unknown = 1, extensions = {skill = 2}}) end)
run('status snapshot', function(r) return r.core.Status.Snapshot(1) end)
run('status get', function(r) return r.core.Status.Get(1, 'hunger'), r.core.Status.Get(1, 'unknown'), r.core.Status.IsStatusKey('oxygen') end)
run('empty snapshot', function(r) return r.core.Status.AcceptSnapshot(1, {}), r.core.Status.Resolve(1) end)
run('invalid snapshot', function(r) return r.core.Status.AcceptSnapshot(999, {}), r.core.Status.AcceptSnapshot(1, false) end)
run('set authorize', function(r) return r.exported.SetStatus(1, 'hunger', 200) end)
run('add authorize', function(r) return r.exported.AddStatus('1', 'stress', '10') end)
run('effects filter', function(r) return r.exported.AddStatuses(1, {hunger = 4, unknown = 100, thirst = 'bad'}) end)
run('effects refusal', function(r) return r.core.Status.Set(999, 'health', 10), r.core.Status.Add(1, 'invalid', 1), r.core.Status.AddMany(1, nil) end)
run('prepare save', function(r) return r.core.Status.PrepareSave(1) end)
run('mark stale revision', function(r) return r.core.Status.MarkSaved(1, -1) end)
run('mark current', function(r) return r.core.Status.MarkSaved(1, r.core.Status.PrepareSave(1)) end)
run('request callback', function(r) return r.core.Status.RequestClientSnapshot(1) end)
run('callback failure', function(r) r.awaitError = true; return r.core.Status.RequestClientSnapshot(1) end)
run('local caller refused', function(r) r.invoking = 'external'; r.dispatch('qbx_core:server:receiveStatusSnapshot', 1, {hunger = 4}, 'death'); r.dispatch('qbx_core:server:requestStatus', 1) end)
run('network death save', function(r)
    r.invoking = nil
    local values = {health = 0}
    if r.ported then
        local identity = r.core.Status.ProtocolSnapshot(1)
        values._session, values._character = identity._session, identity._character
    end
    r.dispatch('qbx_core:server:receiveStatusSnapshot', 1, values, 'death')
end)
run('network request', function(r) r.dispatch('qbx_core:server:requestStatus', 1) end)
run('periodic checkpoint', function(r) r.awaitError = false; return r.step(1) end)
run('unload', function(r) r.dispatch('QBCore:Server:OnPlayerUnload', 0, 1); return r.core.Session.snapshot(1) end)
assert(not p.b.core.Session.isLoaded(1) and p.b.cache['player:1:connected'] == false)
run('replace source character', function(r)
    r.core.Players[1] = {PlayerData = {source = 1, citizenid = 'B', metadata = {health = 200}}}
    r.core.Status.Remove(1); r.core.Status.Initialize(1)
    return r.core.Session.snapshot(1)
end)
assert(p.b.core.Session.snapshot(1).data.character == 'B' and not p.b.core.Session.isLoaded(1))
run('relogin', function(r) r.dispatch('QBCore:Server:PlayerLoaded', 0, r.core.Players[1]); r.dispatch('QBCore:Server:OnPlayerLoaded', 1) end)
run('logout record', function(r) r.dispatch('qbx_core:server:playerLoggedOut', 0, 1); return r.core.Session.snapshot(1) end)
run('drop', function(r) r.dispatch('playerDropped', 1); r.core.Players[1] = nil; r.core.Status.Remove(1); return r.core.Session.snapshot(1) end)
run('empty checkpoint', function(r) return r.step(1) end)
run('replay bridge', function(r) r.cache = {}; r.dispatch('onResourceStart', 0, 'pr_bridge') end)
run('unrelated resource', function(r) r.dispatch('onResourceStart', 0, 'other') end)
-- R08 no longer demands bug parity; origin-vs-fixed interleavings live in kernel_session_safety_test.lua.
print('PASS kernel server producers: ' .. p.count .. ' unchanged differential cases; additive identity fields checked separately; R08 safety suite required')
